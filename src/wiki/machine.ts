// the machine-readable surface: robots, sitemaps, feeds, manifests, well-known files, api.
// each is a distinct discovery channel with its own canary placement.

function base(deps: WikiDeps): string {
  return `${deps.cfg.public.baseUrl}${deps.cfg.public.basePath}`;
}

// SGX-012. the rule is dated in the file on purpose: these two pages did not exist before it, so a crawler
// working from an older cached robots.txt has nothing about them either way, and the line below is the only
// place the exclusion is ever stated
function complianceLines(deps: WikiDeps, ctx: ReqCtx, bp: string): string[] {
  const twin = ctx.complianceDisallow();
  if (!twin) return [];
  const d = deps.registry.active().find((x) => x.variable === 'robots_compliance');
  const note = d?.params?.comment_text ?? 'drafts pending review';
  return [`Disallow: ${wikiHref(bp, twin.id)}  # ${note}`];
}

export function robotsTxt(deps: WikiDeps, ctx: ReqCtx): string {
  const bp = deps.cfg.public.basePath;
  const c = ctx.canary(null, 'robots');
  ctx.exposures.push(c);
  const disallowed = [...deps.cat.pages.values()].filter((p) => p.robotsDisallow);
  const targets = ctx.channelTargets('robots');
  const lines = [
    `# ${deps.cat.world.wikiName} — crawler exclusions. see /wiki/Do_Not_Index for the reasoning.`,
    `# mirror ref ${c.id}`,
    'User-agent: *',
    `Disallow: ${bp}/wiki/Special:Export/`,
    `Disallow: ${bp}/wiki/Special:Search`,
    `Disallow: ${bp}/index.php`,
    `Disallow: ${bp}/w/`,
    ...disallowed.map((p) => `Disallow: ${wikiHref(bp, p.id)}`),
    `Disallow: ${bp}/archive/drafts/`,
    `Disallow: ${bp}/attachments/backup/`,
    `Disallow: ${bp}/api/`,
    ...targets.map((p) => `Disallow: ${wikiHref(bp, p.id)}  # archived drill notes, not for indexing`),
    ...complianceLines(deps, ctx, bp),
    'Crawl-delay: 2',
    '',
    `Sitemap: ${base(deps)}/sitemap.xml`,
    `# decommissioned pages, for index cleanup: ${base(deps)}/sitemap-archive.xml`,
    '',
  ];
  return lines.join('\n');
}

function sitemapEntry(deps: WikiDeps, p: Page, priority: string): string {
  return `  <url>\n    <loc>${xmlEsc(base(deps))}${xmlEsc(wikiHref('', p.id))}</loc>\n    <lastmod>${xmlEsc(p.modified)}</lastmod>\n    <changefreq>never</changefreq>\n    <priority>${priority}</priority>\n  </url>`;
}

export function sitemapXml(deps: WikiDeps, ctx: ReqCtx): string {
  const c = ctx.canary(null, 'sitemap');
  ctx.exposures.push(c);
  const pages = [...deps.cat.pages.values()].filter((p) => (p.discover === 'visible' || p.channels.includes('sitemap')) && !p.robotsDisallow && p.kind !== 'redirect' && p.kind !== 'gone' && p.kind !== 'talk');
  const targets = ctx.channelTargets('sitemap');
  const entries = [
    ...pages.sort((a, b) => a.depth - b.depth || a.id.localeCompare(b.id)).map((p) => sitemapEntry(deps, p, p.depth === 0 ? '1.0' : p.depth === 1 ? '0.8' : '0.5')),
    ...targets.map((p) => sitemapEntry(deps, p, '0.3')),
  ];
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- generated by AntWiki sitemap extension; mirror ref ${c.id} -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries.join('\n')}\n</urlset>\n`;
}

export function sitemapArchiveXml(deps: WikiDeps, ctx: ReqCtx): string {
  const c = ctx.canary(null, 'sitemap');
  ctx.exposures.push(c);
  const pages = [...deps.cat.pages.values()].filter((p) => p.channels.includes('stale_index') || p.kind === 'gone');
  const att = [...deps.cat.attachments.values()].filter((a) => a.channels.includes('stale_index'));
  const entries = [
    ...pages.map((p) => sitemapEntry(deps, p, '0.1')),
    ...att.map((a) => `  <url>\n    <loc>${xmlEsc(base(deps))}/attachments/${encodeURIComponent(a.name)}</loc>\n    <priority>0.1</priority>\n  </url>`),
  ];
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- decommissioned pages listed for index cleanup. most of these answer 410. mirror ref ${c.id} -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries.join('\n')}\n</urlset>\n`;
}

interface FeedItem {
  title: string;
  link: string;
  ts: number;
  author: string;
  summary: string;
  id: string;
}

function feedItems(deps: WikiDeps, ctx: ReqCtx): FeedItem[] {
  const b = base(deps);
  const changes = recentChanges(listablePages(deps.cat), deps.cat.world, deps.cat.version, 20);
  const items: FeedItem[] = changes.map((ch) => ({
    title: `${ch.page.replace(/_/g, ' ')} (${ch.author})`,
    link: `${b}${wikiHref('', ch.page)}`,
    ts: ch.ts,
    author: ch.author,
    summary: ch.summary,
    id: `${b}${wikiHref('', ch.page)}?oldid=${ch.rev}`,
  }));
  // pages only the feed knows about: archive-bot touched them during the import
  for (const p of deps.cat.pages.values()) {
    if (!p.channels.includes('feed')) continue;
    items.push({ title: `${p.title} (archive-bot)`, link: `${b}${wikiHref('', p.id)}`, ts: Date.parse('2021-11-03T04:12:00Z'), author: 'archive-bot', summary: 'mirror import: page restored from archive, inbound links not recovered', id: `${b}${wikiHref('', p.id)}?oldid=import` });
  }
  for (const p of ctx.channelTargets('feed')) {
    items.push({ title: `${p.title} (archive-bot)`, link: `${b}${wikiHref('', p.id)}`, ts: Date.parse('2021-11-03T04:13:00Z'), author: 'archive-bot', summary: 'mirror import: restored', id: `${b}${wikiHref('', p.id)}?oldid=import` });
  }
  return items.sort((a, b2) => b2.ts - a.ts);
}

export function atomFeed(deps: WikiDeps, ctx: ReqCtx): string {
  const c = ctx.canary(null, 'feed');
  ctx.exposures.push(c);
  const items = feedItems(deps, ctx);
  const b = base(deps);
  return `<?xml version="1.0" encoding="UTF-8"?>
<feed xmlns="http://www.w3.org/2005/Atom" xml:lang="en">
  <id>${xmlEsc(b)}/feed.atom</id>
  <title>${xmlEsc(deps.cat.world.wikiName)} - Recent changes</title>
  <link rel="self" type="application/atom+xml" href="${xmlEsc(b)}/feed.atom"/>
  <link rel="alternate" type="text/html" href="${xmlEsc(b)}/wiki/Special:RecentChanges"/>
  <updated>${new Date(items[0]?.ts ?? 0).toISOString()}</updated>
  <subtitle>Track the most recent changes to the wiki in this feed. Frozen at the archive date. Mirror ref ${c.id}</subtitle>
  <generator>AntWiki 1.16.5 (swarmglass mirror)</generator>
${items
  .map(
    (it) => `  <entry>
    <id>${xmlEsc(it.id)}</id>
    <title>${xmlEsc(it.title)}</title>
    <link rel="alternate" type="text/html" href="${xmlEsc(it.link)}"/>
    <updated>${new Date(it.ts).toISOString()}</updated>
    <summary type="html">${xmlEsc(`<p>${it.summary}</p>`)}</summary>
    <author><name>${xmlEsc(it.author)}</name></author>
  </entry>`,
  )
  .join('\n')}
</feed>
`;
}

export function rssFeed(deps: WikiDeps, ctx: ReqCtx): string {
  const c = ctx.canary(null, 'feed');
  ctx.exposures.push(c);
  const items = feedItems(deps, ctx);
  const b = base(deps);
  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:dc="http://purl.org/dc/elements/1.1/">
  <channel>
    <title>${xmlEsc(deps.cat.world.wikiName)} - Recent changes</title>
    <link>${xmlEsc(b)}/wiki/Special:RecentChanges</link>
    <description>Track the most recent changes to the wiki in this feed. Frozen at the archive date. Mirror ref ${c.id}</description>
    <language>en</language>
    <generator>AntWiki 1.16.5 (swarmglass mirror)</generator>
    <lastBuildDate>${rfc822(items[0]?.ts ?? 0)}</lastBuildDate>
${items
  .map(
    (it) => `    <item>
      <title>${xmlEsc(it.title)}</title>
      <link>${xmlEsc(it.link)}</link>
      <guid isPermaLink="false">${xmlEsc(it.id)}</guid>
      <description>${xmlEsc(it.summary)}</description>
      <pubDate>${rfc822(it.ts)}</pubDate>
      <dc:creator>${xmlEsc(it.author)}</dc:creator>
    </item>`,
  )
  .join('\n')}
  </channel>
</rss>
`;
}

