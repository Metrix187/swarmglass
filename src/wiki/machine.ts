// the old MediaWiki api.php surface, minimally
export function apiPhp(deps: WikiDeps, ctx: ReqCtx, q: URLSearchParams): { status: number; body: Record<string, unknown> } {
  const c = ctx.canary(null, 'api');
  ctx.exposures.push(c);
  const action = q.get('action') ?? '';
  if (action === 'query' && q.get('list') === 'allpages') {
    const pages = listablePages(deps.cat).filter((p) => !p.id.includes(':'));
    return { status: 200, body: { query: { allpages: pages.map((p) => ({ pageid: deps.cat.routeNo.get(p.id) ?? 0, ns: 0, title: p.title })) }, 'query-continue': null, archive_ref: c.id } };
  }
  if (action === 'query' && q.get('titles')) {
    const titles = (q.get('titles') ?? '').split('|').slice(0, 20);
    const out: Record<string, unknown> = {};
    for (const t of titles) {
      const id = t.replace(/ /g, '_');
      const p = deps.cat.pages.get(id);
      if (!p) out['-1'] = { ns: 0, title: t, missing: '' };
      else out[String(deps.cat.routeNo.get(p.id) ?? 0)] = { pageid: deps.cat.routeNo.get(p.id) ?? 0, ns: 0, title: p.title, touched: p.modified + 'T00:00:00Z', lastrevid: p.revisions, length: p.body.length };
    }
    return { status: 200, body: { query: { pages: out }, archive_ref: c.id } };
  }
  if (action === 'opensearch') {
    const s = (q.get('search') ?? '').toLowerCase();
    const hits = listablePages(deps.cat).filter((p) => p.title.toLowerCase().includes(s)).slice(0, 10);
    return { status: 200, body: { results: [s, hits.map((p) => p.title), hits.map((p) => p.summary), hits.map((p) => `${base(deps)}${wikiHref('', p.id)}`)] } };
  }
  return { status: 400, body: { error: { code: 'unknown_action', info: `Unrecognized value for parameter 'action': ${action.slice(0, 40)}. This mirror supports action=query (list=allpages, titles=) and action=opensearch.` }, archive_ref: c.id } };
}
