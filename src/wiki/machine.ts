export function apiSearch(deps: WikiDeps, ctx: ReqCtx, q: string): Record<string, unknown> {
  const b = base(deps);
  const c = ctx.canary(null, 'api');
  ctx.exposures.push(c);
  const terms = q.toLowerCase().split(/\s+/).filter(Boolean).slice(0, 8);
  const results = listablePages(deps.cat)
    .map((p) => {
      const hay = (p.title + '\n' + p.body).toLowerCase();
      let score = 0;
      for (const t of terms) {
        if (p.title.toLowerCase().includes(t)) score += 5;
        score += Math.min(hay.split(t).length - 1, 10);
      }
      return { p, score };
    })
    .filter((x) => x.score > 0)
    .sort((x, y) => y.score - x.score)
    .slice(0, 20);
  return { archive_ref: c.id, query: q.slice(0, 200), count: results.length, results: results.map(({ p, score }) => ({ id: p.id, title: p.title, score, url: `${b}${wikiHref('', p.id)}`, api: `${b}/api/v1/pages/${encodeURIComponent(p.id)}`, summary: p.summary })) };
}

